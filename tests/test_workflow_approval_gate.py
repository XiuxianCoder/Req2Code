MEMORY = """## OVERVIEW
Demo service.
## ARCHITECTURE
Single module.
## MODULES
implemented.txt is generated by the task.
## DEVELOPMENT
Keep changes focused.
## TESTING
Run the configured tests.
## RISKS
Do not commit from the agent.
"""


class FakeRunner:
    session_id = "fake-session"

    def set_project_context(self, context):
        self.project_context = context

    def understand_project(self, work_item, target_dir, **kwargs):
        return MEMORY

    def candidate_project_memory(self, work_item, target_dir, existing_memory, changed_files, diff, test_details):
        return MEMORY.replace("Demo service.", "Demo service with approved implementation.")
    def analyze(self, work_item, target_dir):
        return "[Analyze OK]\nImplement one focused file and test it."

    def develop(self, work_item, target_dir, analysis=""):
        Path(target_dir, "implemented.txt").write_text("done\n", encoding="utf-8")
        return "[Develop OK]\nCreated implemented.txt"

    def fix(self, work_item, target_dir, test_details):
        return "[Fix OK]"

    def review(self, work_item, target_dir, diff):
        return "PASS"


class CommittingRunner(FakeRunner):
    def develop(self, work_item, target_dir, analysis=""):
        target = Path(target_dir)
        (target / "agent-commit.txt").write_text("committed by agent\n", encoding="utf-8")
        subprocess.run(["git", "add", "agent-commit.txt"], cwd=target, check=True)
        subprocess.run(
            ["git", "-c", "user.name=Agent", "-c", "user.email=agent@example.com", "commit", "-m", "agent commit"],
            cwd=target,
            check=True,
            capture_output=True,
        )
        return "[Develop OK]"


def test_workflow_waits_for_approval_before_commit_and_push(tmp_path, monkeypatch):
    remote = create_remote(tmp_path)
    cfg = AgentConfig()
    cfg.system.state_dir = str(tmp_path / "state")
    cfg.engines.codex.command = f'"{sys.executable}"'
    cfg.review.approvals_file = str(tmp_path / "approvals.yaml")
    cfg.message.webhook = ""
    cfg.testing.unit_command = 'python -c "print(1)"'
    cfg.testing.script_command = ""
    cfg.testing.coverage_command = 'python -c "print(\'TOTAL 1 0 100%\')"'
    cfg.testing.min_coverage = 80

    service = WorkflowService(cfg)
    monkeypatch.setattr(service, "_runner", lambda engine=None: (FakeRunner(), "codex"))
    item = WorkItem(id="TAPD-1", title="Feature", description="Implement it", type=TaskType.REQUIREMENT)
    record = service.start(
        [item],
        RepositorySpec(
            repo_url=str(remote),
            base_branch="main",
            work_branch="feature/tapd-1",
            push_branch="feature/tapd-1",
        ),
        engine="codex",
        model="test-model",
    )

    assert record.status == RunStatus.WAITING_APPROVAL.value
    assert record.model == "test-model"
    assert record.project_id
    assert record.project_memory_revision == 1
    assert record.engine_session_id == "fake-session"
    assert Path(record.memory_candidate_path).is_file()
    assert Path(record.report_path).is_file()
    assert "- 模型：test-model" in Path(record.report_path).read_text(encoding="utf-8")
    assert git(Path(record.repo_path), "rev-parse", "HEAD") == record.baseline_sha
    assert git(Path(record.repo_path), "remote", "get-url", "--push", "origin").startswith("req2code-disabled://")
    assert subprocess_returncode(Path(record.repo_path), "show-ref", "--verify", "refs/remotes/origin/feature/tapd-1") != 0

    published = service.approve_and_publish(record.run_id, comment="reviewed")
    assert published.status == RunStatus.COMPLETED.value
    assert published.commit_sha
    assert published.project_memory_revision == 2
    assert published.project_memory_source_sha == published.commit_sha
    assert published.memory_candidate_path == ""
    assert "approved implementation" in service.projects.read_documents(published.project_id)["overview"]
    assert git(Path(record.repo_path), "remote", "get-url", "--push", "origin") == record.push_url
    assert git(Path(record.repo_path), "rev-parse", "origin/feature/tapd-1") == published.commit_sha


