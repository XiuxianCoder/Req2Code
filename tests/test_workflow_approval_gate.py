def test_current_agent_transient_finalization_error_is_retryable_and_keeps_push_disabled(tmp_path, monkeypatch):
    remote = create_remote(tmp_path)
    cfg = AgentConfig()
    cfg.system.state_dir = str(tmp_path / "state")
    cfg.review.approvals_file = "approvals.yaml"
    cfg.message.webhook = ""
    service = WorkflowService(cfg)
    record = service.begin_agent_run(
        [WorkItem(id="TAPD-TRANSIENT", title="Retry finalization", description="Retry safely", type=TaskType.BUG)],
        RepositorySpec(
            repo_url=str(remote),
            base_branch="main",
            work_branch="feature/transient-finalization",
            push_branch="feature/transient-finalization",
        ),
        agent_name="codex",
    )
    (Path(record.repo_path) / "transient.txt").write_text("done\n", encoding="utf-8")
    original_assert_baseline = service.workspace.assert_baseline
    attempts = 0

    def fail_once(*args, **kwargs):
        nonlocal attempts
        attempts += 1
        if attempts == 1:
            raise RepositoryError("temporary local Git validation error")
        return original_assert_baseline(*args, **kwargs)

    monkeypatch.setattr(service.workspace, "assert_baseline", fail_once)
    with pytest.raises(RepositoryError, match="temporary local Git validation error"):
        service.finalize_agent_run(
            record.run_id,
            implementation_plan="实现并验证所选缺陷。",
            implementation_summary="已实现并补充回归测试。",
            test_evidence="聚焦测试：2 passed",
        )

    interrupted = service.runs.require(record.run_id)
    assert interrupted.status == RunStatus.DEVELOPING.value
    assert interrupted.analysis == "实现并验证所选缺陷。"
    assert interrupted.agent_test_evidence == "聚焦测试：2 passed"
    assert interrupted.verification_count == 1
    assert git(Path(record.repo_path), "remote", "get-url", "--push", "origin").startswith("req2code-disabled://")
    assert "开发中（可继续收尾）" in Path(interrupted.report_path).read_text(encoding="utf-8")

    finalized = service.finalize_agent_run(
        record.run_id,
        implementation_plan="实现并验证所选缺陷。",
        implementation_summary="已实现并补充回归测试。",
        test_evidence="聚焦测试：2 passed",
    )
    assert finalized.status == RunStatus.WAITING_APPROVAL.value
    assert finalized.verification_count == 2
    assert git(Path(record.repo_path), "remote", "get-url", "--push", "origin").startswith("req2code-disabled://")


